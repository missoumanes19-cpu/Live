String t(String ar) => AppSettings.lang == 'en' ? (_en[ar] ?? ar)
    : AppSettings.lang == 'fr' ? (_fr[ar] ?? _en[ar] ?? ar) : ar;

class AppSettings extends ChangeNotifier {
  static String lang = 'ar';
  Box get _b => Hive.box('settings');

  AppSettings() { lang = (_b.get('lang', defaultValue: 'ar') as String); }

  void setLanguage(String v) { lang = v; _b.put('lang', v); notifyListeners(); }

  String get decoder => _b.get('decoder', defaultValue: 'auto') as String; // auto | hw | sw
  void setDecoder(String v) { _b.put('decoder', v); notifyListeners(); }
  static String hwdec(String d) =>
      d == 'sw' ? 'no' : 'mediacodec,mediacodec-copy'; // مباشر على السطح ثم نسخ عكسي

  int get fit => _b.get('fit', defaultValue: 0) as int; // 0..3
  void setFit(int v) { _b.put('fit', v); notifyListeners(); }

  double get subSize => (_b.get('subSize', defaultValue: 22.0) as num).toDouble();
  int get subColor => _b.get('subColor', defaultValue: 0xFFFFFFFF) as int;
  int get subBg => _b.get('subBg', defaultValue: 0x99000000) as int;
  void saveSubStyle(double size, int color, int bg) {
    _b.put('subSize', size); _b.put('subColor', color); _b.put('subBg', bg);
  }
  String get liveFormat => _b.get('liveFormat', defaultValue: 'auto') as String; // auto | ts | m3u8
  void setLiveFormat(String v) { _b.put('liveFormat', v); notifyListeners(); }
  bool get lite => _b.get('lite', defaultValue: false) as bool;
  void setLite(bool v) { _b.put('lite', v); applyPerformanceMode(v); notifyListeners(); }
  /// قيم فعلية: في وضع الأجهزة الضعيفة نقلّل الذاكرة والتخزين المؤقت
  int get effBufferMb => lite && bufferMb > 32 ? 32 : bufferMb;
  int get effPrebufferSec => lite && prebufferSec > 5 ? 5 : prebufferSec;
  int get prebufferSec => _b.get('prebufferSec', defaultValue: 6) as int;
  void setPrebufferSec(int v) { _b.put('prebufferSec', v); notifyListeners(); }
  int get bufferMb => _b.get('bufferMb', defaultValue: 64) as int;
  void setBufferMb(int v) { _b.put('bufferMb', v); notifyListeners(); }

  Set<String> get hidden => Set<String>.from(
      (_b.get('hidden', defaultValue: <dynamic>[]) as List).map((e) => '$e'));
  void toggleHidden(String c) {
    final s = hidden;
    s.contains(c) ? s.remove(c) : s.add(c);
    _b.put('hidden', s.toList());
    notifyListeners();
  }

  String get player {
    final v = _b.get('player', defaultValue: 'internal') as String; // internal|mx|chooser|custom
    return v == 'ytv' ? 'internal' : v; // تمت إزالة YTV
  }
  void setPlayer(String v) { _b.put('player', v); notifyListeners(); }
  String get customPackage => _b.get('customPackage', defaultValue: '') as String;
  void setCustomPackage(String v) { _b.put('customPackage', v.trim()); notifyListeners(); }
  String get uiStyle => _b.get('uiStyle', defaultValue: 'classic') as String; // classic|modern
  void setUiStyle(String v) { _b.put('uiStyle', v); notifyListeners(); }

  bool get autoSync => _b.get('autoSync', defaultValue: true) as bool;
  void setAutoSync(bool v) { _b.put('autoSync', v); notifyListeners(); }
}

/// يضبط كاش الصور حسب قدرة الجهاز (الأجهزة الضعيفة تستهلك ذاكرة أقل)
void applyPerformanceMode(bool lite) {
  final c = PaintingBinding.instance.imageCache;
  c.maximumSizeBytes = lite ? 30 << 20 : 100 << 20;
  c.maximumSize = lite ? 100 : 1000;
}
